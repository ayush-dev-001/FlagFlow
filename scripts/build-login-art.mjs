// Generates apps/dashboard/src/auth/illustration/artwork.tsx from the owner-supplied Login.svg.
//
//   node scripts/build-login-art.mjs [path/to/Login.svg]
//
// - Repaints the drawing in the site palette (PLAN.md §3): ink and greys, lime screen and accents.
// - Converts it to JSX (no raw HTML injection), prefixes gradient ids so they can't collide on the page,
//   and drops the decorative group ids (the source repeats several).
// - Cuts out the four looping screen elements (avatar, two fields, button) and leaves a `screen` slot,
//   so React can drive them from the real form. Their path data is exported for that.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const source = process.argv[2] ?? join(root, 'apps/dashboard/src/auth/illustration/source/Login.svg');
const out = join(root, 'apps/dashboard/src/auth/illustration/artwork.tsx');
const svg = readFileSync(source, 'utf8');

// Source colour -> site palette.
const PALETTE = {
  // screen and plant gradient -> lime to olive (the home page's featured-plan gradient)
  '#6ad0fb': '#e3f99c',
  '#6783d6': '#c4f04a',
  '#6336b2': '#5f7d2c',
  // hair and beard
  '#774b88': '#4b504d',
  '#5d3a72': '#3b3f3d',
  '#43295d': '#2b2f2d',
  // sweater and sleeves -> the home page's white cards
  '#9a72f6': '#f4f5f4',
  '#865fed': '#dcdfdd',
  '#724ce4': '#c3c7c5',
  '#bb68fa': '#e9ebea',
  '#a961f6': '#d2d5d3',
  '#965bf1': '#babebc',
  // trousers, chair, desk -> greys on ink
  '#33226c': '#2c302e',
  '#31236c': '#2a2e2c',
  '#2f2070': '#272b29',
  '#362478': '#303432',
  '#412d8d': '#383d3a',
  '#533aa9': '#474c49',
  // monitor back and stand
  '#471f5e': '#1c1f1e',
  // yellow accents (pot, shoes, button, tab) -> lime
  '#ffb300': '#c4f04a',
};

const tags = svg.match(/<[^>]+>/g);
if (!tags) throw new Error('no tags');

// The screen's four looping groups: from the avatar wrapper to the end of the button wrapper.
const start = tags.findIndex(
  (t, i) => t.startsWith('<g opacity="0" id=') && tags[i + 1]?.startsWith('<animate'),
);
let depth = 0;
let end = -1;
let groups = 0;
for (let i = start; i < tags.length; i++) {
  const t = tags[i];
  if (t.startsWith('</g')) depth--;
  else if (t.startsWith('<g')) depth++;
  if (depth === 0 && t.startsWith('</g')) {
    groups++;
    if (groups === 4) {
      end = i;
      break;
    }
  }
}
if (start < 0 || end < 0) throw new Error('screen groups not found');

// Path data and anchor of each screen element (the inner matrix group holds the resting position).
const screenParts = [];
for (let i = start; i <= end; i++) {
  const m = /matrix\(1,0,0,1,([-\d.]+),([-\d.]+)\)/.exec(tags[i]);
  const p = tags[i + 1] && /<path fill="([^"]+)" d="([^"]+)"/.exec(tags[i + 1]);
  if (m && p) screenParts.push({ x: Number(m[1]), y: Number(m[2]), d: p[2] });
}
if (screenParts.length !== 4) throw new Error(`expected 4 screen parts, got ${screenParts.length}`);

// The screen panel itself (its gradient path), for success/error tints.
const panelIdx = tags.findIndex((t) => t.includes('fill="url(#i0)"'));
const panelAnchor = /matrix\(1,0,0,1,([-\d.]+),([-\d.]+)\)/.exec(tags[panelIdx - 1]);
const panelD = /d="([^"]+)"/.exec(tags[panelIdx])[1];

const recolour = (v) => PALETTE[v.toLowerCase()] ?? v;

function toJsx(tag) {
  if (tag.startsWith('</')) return tag;
  return tag
    .replace(/\s(stop-color)="([^"]+)"/g, (_m, _a, v) => ` stopColor="${recolour(v)}"`)
    .replace(/\sfill="(#[0-9a-fA-F]{6})"/g, (_m, v) => ` fill="${recolour(v)}"`)
    .replace(/\sxmlns:xlink="[^"]*"/, '')
    .replace(/url\(#i(\d+)\)/g, 'url(#ffl-i$1)')
    .replace(/<linearGradient id="i(\d+)"/g, '<linearGradient id="ffl-i$1"')
    .replace(/(<(?!linearGradient)[a-zA-Z]+[^>]*?)\sid="[^"]*"/g, '$1')
    .replace(
      /^<svg[^>]*>/,
      '<svg viewBox="0 0 2000 2000" fill="none" xmlns="http://www.w3.org/2000/svg" className={className} aria-hidden="true" focusable="false">',
    )
    .replace(/(?<!\/)>$/, (m) => m);
}

const body = [...tags.slice(0, start).map(toJsx), '{screen}', ...tags.slice(end + 1).map(toJsx)].join('\n');

const file = `// GENERATED by scripts/build-login-art.mjs from illustration/source/Login.svg (owner-supplied artwork,
// recoloured to the site palette). Do not edit by hand: change the generator and re-run it.
import type { ReactNode } from 'react';

export interface ScreenPart {
  x: number;
  y: number;
  d: string;
}

/** Resting anchor and path of the avatar, the two field lines and the button on the monitor. */
export const SCREEN_PARTS: { avatar: ScreenPart; field1: ScreenPart; field2: ScreenPart; button: ScreenPart } = ${JSON.stringify(
  { avatar: screenParts[0], field1: screenParts[1], field2: screenParts[2], button: screenParts[3] },
  null,
  2,
)};

/** The monitor's screen panel, for tinting on success or error. */
export const SCREEN_PANEL: ScreenPart = ${JSON.stringify({ x: Number(panelAnchor[1]), y: Number(panelAnchor[2]), d: panelD }, null, 2)};

/** The full drawing; \`screen\` is rendered where the monitor's form sits. */
export function Artwork({ screen, className }: { screen: ReactNode; className?: string }) {
  return (
${body}
  );
}
`;

writeFileSync(out, file);
console.log(`wrote ${out}: ${tags.length - (end - start + 1)} tags, screen slot replaces ${end - start + 1}`);
